def clean_inference(raw) -> tuple[str, str, dict]:
    if not isinstance(raw, dict) or set(raw) != {"provider", "model"}:
        raise ValueError("invalid inference selection")
    provider_id = raw.get("provider")
    model = raw.get("model")
    if provider_id not in INFERENCE_PRESETS:
        raise ValueError("unknown inference provider")
    if not isinstance(model, str) or not _MODEL_RE.fullmatch(model.strip()):
        raise ValueError("invalid inference model")
    model = model.strip()
    preset = INFERENCE_PRESETS[provider_id]
    if preset["model_locked"] and model != preset["default_model"]:
        raise ValueError("sponsored model is fixed")
    if not os.environ.get(preset["env"], "").strip():
        raise RuntimeError("selected inference provider is not configured")
    return provider_id, model, preset


def prepare_visual_inference(safe_input, provider_id, model):
    """Preserve the verified text fallback without pretending it saw pixels."""
    if (provider_id, model) != ('openrouter', 'z-ai/glm-5.2'):
        return safe_input
    text_input, visual = visual_input(safe_input)
    if visual:
        text_input['scene'].pop('visual', None)
        text_input['scene']['visualUnavailable'] = 'selected-model-text-only'
    return text_input


class _HTTPTransport:
    def __init__(self, url: str, env_var: str, timeout: int):
        self.url = url
        self.env_var = env_var
        self.timeout = timeout

    def _token(self) -> str:
        token = os.environ.get(self.env_var, "").strip()
        if not token:
            raise RuntimeError("%s provider placeholder unavailable" % self.env_var)
        return token

    def _request(self, payload: dict, headers: dict) -> dict:
        request = urllib.request.Request(
            self.url,
            data=json.dumps(payload, separators=(",", ":")).encode("utf-8"),
            headers=headers,
            method="POST",
        )
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                raw = response.read(1024 * 1024 + 1)
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8", errors="replace")[:300]
            raise RuntimeError("HTTP %s: %s" % (exc.code, detail)) from exc
        except urllib.error.URLError as exc:
            raise RuntimeError("network failure: " + str(exc.reason)) from exc
        if len(raw) > 1024 * 1024:
            raise RuntimeError("inference response too large")
        decoded = json.loads(raw.decode("utf-8"))
        if not isinstance(decoded, dict):
            raise RuntimeError("inference backend returned a non-object")
        return decoded


class OpenAICompatibleTransport(_HTTPTransport):
    def complete(self, model: str, safe_input: dict, max_tokens: int) -> str:
        text_input, visual = visual_input(safe_input)
        content = json.dumps(text_input, separators=(",", ":"), sort_keys=True)
        if visual:
            content = [{"type": "text", "text": content},
                       {"type": "image_url", "image_url": {"url": visual['image']}}]
        body = self._request({
            "model": model,
            "messages": [
                {"role": "system", "content": prompt_for_input(text_input)},
                {"role": "user", "content": content},
            ],
            # Reasoning consumes completion budget too. Keep visible output
            # schema-bounded while allowing the sponsored model to finish.
            "max_tokens": 4096 if self.env_var == 'ASI_API_KEY' else min(int(max_tokens), 1200),
            **({'reasoning_effort': 'low'} if self.env_var == 'ASI_API_KEY' else {}),
        }, {
            "Content-Type": "application/json",
            "Authorization": "Bearer " + self._token(),
        })
        return _extract_content(body)


class AnthropicTransport(_HTTPTransport):
    def complete(self, model: str, safe_input: dict, max_tokens: int) -> str:
        text_input, visual = visual_input(safe_input)
        content = json.dumps(text_input, separators=(",", ":"), sort_keys=True)
        if visual:
            content = [{"type": "text", "text": content},
                       {"type": "image", "source": {"type": "base64",
                        "media_type": "image/jpeg", "data": visual['image'].split(',', 1)[1]}}]
        body = self._request({
            "model": model,
            "system": prompt_for_input(text_input),
            "messages": [{
                "role": "user",
                "content": content,
            }],
            "max_tokens": min(int(max_tokens), 1200),
        }, {
            "Content-Type": "application/json",
            "x-api-key": self._token(),
            "anthropic-version": "2023-06-01",
        })
        blocks = body.get("content")
        if not isinstance(blocks, list):
            raise ValueError("missing content")
        text = "".join(
            block.get("text", "")
            for block in blocks
            if isinstance(block, dict) and block.get("type") == "text"
        ).strip()
        if not text:
            raise ValueError("missing content")
        return text

def _finite_number(value):
    if isinstance(value, bool):
        raise ValueError("boolean is not numeric")
    number = float(value)
    if not math.isfinite(number):
        raise ValueError("non-finite number")
    return number


def _clean_target(raw):
    if not isinstance(raw, dict):
        raise ValueError("invalid target")
    kind = raw.get("kind")
    if kind == "sticker" and set(raw) == {"kind", "id"}:
        sticker_id = raw.get("id")
        if isinstance(sticker_id, str) and 0 < len(sticker_id) <= 160:
            return {"kind": "sticker", "id": sticker_id}
        raise ValueError("invalid sticker target")
    if kind == "point" and set(raw) == {"kind", "x", "y"}:
        x = _finite_number(raw.get("x"))
        y = _finite_number(raw.get("y"))
        if 0.0 <= x <= 1.0 and 0.0 <= y <= 1.0:
            return {"kind": "point", "x": x, "y": y}
    raise ValueError("invalid target")


def clean_goal(raw):
    """Validate the same semantic envelope the host validates again."""
    if raw is None:
        return None
    if not isinstance(raw, dict) or set(raw) - _ALLOWED_GOAL_FIELDS:
        raise ValueError("invalid goal fields")

    subject = raw.get("subject")
    if not isinstance(subject, str) or not subject or len(subject) > 160:
        raise ValueError("invalid goal subject")
    intent = raw.get("intent", "control")
    if intent not in _ALLOWED_INTENTS:
        raise ValueError("invalid goal intent")

    if intent in ("remember-pattern", "perform-pattern"):
        if set(raw) - {"subject", "intent", "label", "pattern"}:
            raise ValueError("invalid pattern goal fields")
        goal = {"subject": subject, "intent": intent}
        label = raw.get("label")
        if label is not None:
            # Match the host's valid_label bound and canonical whitespace.
            if not isinstance(label, str) or not 0 < len(label.strip()) <= 48 \
                    or any(ch in ":\r\n\t" for ch in label):
                raise ValueError("invalid pattern label")
            goal["label"] = " ".join(label.split())
        reference = raw.get("pattern")
        if reference is not None:
            if not isinstance(reference, str) or not reference \
                    or len(reference) > 64 or ":" in reference:
                raise ValueError("invalid pattern reference")
            goal["pattern"] = reference
        if intent == "remember-pattern" and "label" not in goal:
            raise ValueError("missing pattern label")
        if intent == "perform-pattern" and not ({"label", "pattern"} & goal.keys()):
            raise ValueError("missing pattern reference")
        return goal
    if {"label", "pattern"} & raw.keys():
        raise ValueError("pattern fields require pattern intent")

    if intent in _DEMONSTRATION_INTENTS:
        frames = _DEMONSTRATION_INTENTS[intent]
        fields = {"subject", "intent", "demonstration"}
        if frames:
            fields.add("frame")
        if set(raw) != fields:
            raise ValueError("invalid demonstration goal fields")
        event_id = raw["demonstration"]
        if not isinstance(event_id, str) or not _INPUT_EVENT_RE.fullmatch(event_id):
            raise ValueError("invalid demonstration reference")
        goal = {"subject": subject, "intent": intent, "demonstration": event_id}
        if frames:
            if raw["frame"] not in frames:
                raise ValueError("invalid trajectory frame")
            goal["frame"] = raw["frame"]
        return goal
    if {"demonstration", "frame"} & raw.keys():
        raise ValueError("trajectory fields require demonstration intent")

    goal = {"subject": subject, "intent": intent}

    if "behavior" in raw:
        behavior = raw["behavior"]
        if not isinstance(behavior, str) or not behavior or len(behavior) > 80:
            raise ValueError("invalid goal behavior")
        goal["behavior"] = behavior

    if "target" in raw:
        goal["target"] = _clean_target(raw["target"])

    if "facing" in raw:
        facing = raw["facing"]
        if facing not in ("left", "right"):
            raise ValueError("invalid goal facing")
        goal["facing"] = facing

    if "scale" in raw:
        scale = _finite_number(raw["scale"])
        if not 0.90 <= scale <= 1.10:
            raise ValueError("invalid goal scale")
        goal["scale"] = scale

    return goal


def validate_demonstration_goal(goal, scene):
    """Admit only a supported event offered in this turn's bounded scene."""
    if goal is None or goal.get("intent") not in _DEMONSTRATION_INTENTS:
        return
    if _DEMONSTRATION_INTENTS[goal["intent"]]:
        stickers = scene.get("stickers") if isinstance(scene, dict) else None
        if not isinstance(stickers, list) or not any(
                isinstance(sticker, dict) and sticker.get("id") == goal["subject"]
                for sticker in stickers):
            raise ValueError("trajectory subject not visible")
    interaction = scene.get("interaction") if isinstance(scene, dict) else None
    signals = interaction.get("signals") if isinstance(interaction, dict) else None
    if not isinstance(signals, list):
        raise ValueError("missing current interaction")
    if any(isinstance(signal, dict)
               and signal.get("kind") == "page-path"
               and signal.get("sourceEvent") == goal["demonstration"]
               for signal in signals):
        return
    pending = scene.get("pendingReference")
    if isinstance(pending, dict) and pending.get("kind") == "page-path" \
            and pending.get("demonstration") == goal["demonstration"] \
            and pending.get("subject") == goal["subject"]:
        return
    raise ValueError("demonstration not in current interaction or pending reference")


def _extract_content(body: dict) -> str:
    choices = body.get("choices")
    if not isinstance(choices, list) or not choices:
        raise ValueError("missing choices")
    first = choices[0]
    if not isinstance(first, dict):
        raise ValueError("invalid choice")
    message = first.get("message")
    if not isinstance(message, dict):
        raise ValueError("invalid message")
    content = message.get("content")
    if not isinstance(content, str) or not content.strip():
        raise ValueError('inference-output-budget' if first.get('finish_reason') == 'length' else 'inference-empty-content')
    return content.strip()


def _parse_json_object(text: str) -> dict:
    """Strict JSON first; tolerate only a single fenced JSON object."""
    candidate = text.strip()
    if candidate.startswith("```") and candidate.endswith("```"):
        lines = candidate.splitlines()
        if len(lines) >= 3 and lines[0].strip().lower() in (
                "```json", "```"):
            candidate = "\n".join(lines[1:-1]).strip()
    decoded = json.loads(candidate)
    if not isinstance(decoded, dict):
        raise ValueError("response is not an object")
    return decoded


